"""Набор готовых потенциалов для примеров и тестов.

Сам решатель не привязан к этому модулю: в `MatchedNumerovSolver` можно передать
любую Python-функцию вида `V(x)`. Здесь собраны лишь два удобных варианта:

* асимметричная квартичная двойная яма из задания;
* гармонический осциллятор, спектр которого известен аналитически и потому
  подходит для проверки кода.
"""

from __future__ import annotations

import numpy as np
from numpy.typing import ArrayLike, NDArray


FloatArray = NDArray[np.float64]


def quartic_double_well(
    x: ArrayLike,
    *,
    v0: float = 5.0,
    alpha: float = 0.0,
) -> FloatArray:
    """Вычислить асимметричный потенциал двойной ямы.

    Формула потенциала:

        V(x) = v0 * (x**2 - 1)**2 + alpha*x.

    Parameters
    ----------
    x:
        Одна координата или массив координат. Благодаря `np.asarray` функция
        одинаково работает и со скаляром, и с NumPy-массивом.
    v0:
        Масштаб квартичной части. При `alpha=0` минимумы находятся в `x=±1`
        и имеют нулевую энергию, а значение в центре равно `V(0)=v0`.
    alpha:
        Коэффициент линейного наклона. Положительное `alpha` поднимает правую
        часть потенциала и опускает левую, нарушая чётность `V(x)=V(-x)`.

    Returns
    -------
    FloatArray
        Значения потенциала в тех же координатах, что были переданы в `x`.
    """

    x_arr = np.asarray(x, dtype=float)
    if v0 <= 0:
        # При v0 <= 0 это уже не удерживающая квартичная двойная яма, для
        # которой предназначен данный пример.
        raise ValueError("v0 must be positive for a confining quartic double well")

    # Операции NumPy выполняются покомпонентно сразу для всего массива.
    return v0 * (x_arr**2 - 1.0) ** 2 + alpha * x_arr


def harmonic_oscillator(x: ArrayLike, *, omega: float = 1.0) -> FloatArray:
    """Вычислить потенциал безразмерного гармонического осциллятора.

    Используется формула

        V(x) = omega**2 * x**2 / 2,

    соответствующая единицам `m=ℏ=1`. Точный спектр равен

        E_n = omega * (n + 1/2),

    поэтому этот потенциал используется в автоматическом тесте точности.
    """

    x_arr = np.asarray(x, dtype=float)
    if omega <= 0:
        raise ValueError("omega must be positive")
    return 0.5 * omega**2 * x_arr**2
